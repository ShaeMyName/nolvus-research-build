"""Generate layer C shae.dialogue-actions (TASK_C step 4; spec §11.2, §11.12.2, §11.14.3, §6.5 CF-1) from the reviewed
drafts in DIALOGUE_OVERLAY/ plus two generated blacklists:
  - serana_lines_need_the_player.yaml: quest DLC1NPCMentalModel (Dawnguard 0x002B6E), S-22 pattern;
  - custom_followers_via_bridge_only.yaml: every TIF script on the registry followers' own follow/wait/dismiss/recruit
    topics (build/out/cf1/classified.json, from cf1_topics.py + cf1_classify.py), by script name (base's own
    quest_stage_setter pattern). Serana's and NFF's topics are covered by their quest keys instead.
Not included: 0750_embedded_actions (list B, M6). Output: build/layers/dialogue-actions/SKSE/Plugins/SkyrimNet/external/
shae.dialogue-actions/."""
import json, os

SRC = "C:/nolvus-research/DIALOGUE_OVERLAY/shae.dialogue-actions/"
CF1 = "C:/nolvus-research/build/out/cf1/"
OUT = "C:/nolvus-research/build/layers/dialogue-actions/SKSE/Plugins/SkyrimNet/external/shae.dialogue-actions/"
QUEST_KEYED = {"dawnguard.esm|0x002B6E": "DLC1NPCMentalModel", "nwsfollowerframework.esp|0x00434F": "nwsFollowerController"}


def w(rel, text):
    p = OUT + rel
    os.makedirs(os.path.dirname(p), exist_ok=True)
    open(p, "w", encoding="utf-8", newline="\n").write(text)


def read(p):
    return open(p, encoding="utf-8").read().replace("\r\n", "\n")


m = json.loads(read(SRC + "manifest.json"))
m["description"] = ("Component C of the Errand Bridge build (spec §11.2, §11.12.2, §11.14.3, §6.5 CF-1). Replaces the "
                    "TriggerDialogueLine description (components/dialogue_action.prompt) with clear-intent, clarify, "
                    "decline-and-steer and consequential-line rules, and blacklists follower-command, marriage, RDO, "
                    "Serana and custom-follower dialogue scripts so those go through gated actions only. Private; "
                    "never published.")
m["version"] = "1.0.0"
w("manifest.json", json.dumps(m, indent=2) + "\n")
w("prompts/components/dialogue_action.prompt", read(SRC + "prompts/components/dialogue_action.prompt"))
for f in ("follower_commands_via_actions_only.yaml", "marriage_needs_your_yes.yaml", "rdo_lines_need_the_player.yaml"):
    w("dialogue_actions/" + f, read(SRC + "dialogue_actions/" + f))

w("dialogue_actions/serana_lines_need_the_player.yaml", """kind: lists
name: Serana's own lines need the player
description: >-
  Keeps the LLM from firing any dialogue script of Serana's controller quest (DLC1NPCMentalModel,
  Dawnguard 0x002B6E): her own follow, wait and dismiss lines and everything else that quest owns.
  Her follow state is read by the Errand Bridge (spec 6.5); an AI-fired line would change it behind
  the bridge's back. Pressing E and choosing the line yourself is unaffected. (Spec 6.5, S-22 pattern.)
blacklist:
  - DLC1NPCMentalModel
""")

res = json.load(open(CF1 + "classified.json", encoding="utf-8"))
groups = {}
for x in res:
    if x["quest"] in QUEST_KEYED:
        continue
    g = groups.setdefault(x["npc"], {})
    g.setdefault(x["tif"], set()).add(x["role"])
L = ["kind: lists",
     "name: Custom followers' own commands go through the bridge",
     "description: >-",
     "  Keeps the LLM from firing the custom followers' own follow, wait, dismiss and recruit lines (Inigo,",
     "  Lucien, Remiel, Kaidan's Katana/Megara/Shale, Auri). Their frameworks act outside NFF and SeverActions,",
     "  and the Errand Bridge holds these followers by its own rules (spec 6.5, Mode 4); an AI-fired line would",
     "  recruit, park or dismiss them behind its back. Keys are the lines' fragment script names (base's own",
     "  quest_stage_setter pattern); none of these scripts is used by any other line in the load order (CF-1",
     "  offline scan). Generated by build/tools/gen_layer_c.py. Pressing E and choosing the line yourself is",
     "  unaffected. If test CF-1 shows a name-keyed entry still offered, fall back to the follower's dialogue",
     "  quest listed in build/out/cf1/quest_edids.json.",
     "blacklist:"]
n = 0
for npc in sorted(groups):
    L.append("  # %s" % npc)
    for tif in sorted(groups[npc], key=str.lower):
        L.append("  - %s" % tif)
        n += 1
w("dialogue_actions/custom_followers_via_bridge_only.yaml", "\n".join(L) + "\n")
print("layer C written: custom-follower keys %d (%s); quest keys added: DLC1NPCMentalModel" % (
    n, ", ".join("%s %d" % (k, len(v)) for k, v in sorted(groups.items()))))
