def _import_box(r, n, wait_s=10):
    """After an NFF import with defaults: SetImportLight may show a message box (nwsShowImportSet = 1) that pauses the game.
    Returns 'held' (no ESS_APPLY yet after wait_s: the gate holds), 'applied' (apply already happened: no box shown), then
    answers the box with ENTER either way (INFERRED: first button)."""
    t0 = tail("papyrus")
    time.sleep(wait_s)
    held = not has_line(t0.read(), r"ESS_APPLY actor=%s" % re.escape(n["name"]))
    try:
        import keys
        if keys.focus_game():
            keys.press("ENTER")
            r.log("  import box: ENTER sent")
        else:
            r.log("  import box: game window not focusable, no key sent")
    except Exception as e:      # noqa: BLE001
        r.log("  import box: key route failed %r" % (e,))
    return "held" if held else "applied"


