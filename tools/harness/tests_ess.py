def pick_npcs(r, n=1, **want):
    """Unique, non-essential, loaded market adults of POOL with no NFF seat, SA roster, IEB_Ess key or tracking, brought to
    the player. Returns [dict(fid, name, row, d)]. `want` overrides expectations (e.g. baseess=1 for an authored one)."""
    out = []
    for row, (ref, base) in enumerate(POOL):
        con(r, "%08X.moveto player" % ref)
        time.sleep(3)
        u, name, child = who(r, ref)
        if not u or not name or child:
            continue
        d = ex(r, ref)
        if not d or g(d, "uniq") != 1 or g(d, "child") != 0:
            continue
        exp = dict(baseess=0, fac=0, seat=0, saroster=0, listed=0, ieb_ess=-1, ieb_essfail=-1, ieb_essoptout=-1, ieb_esssusp=-1)
        exp.update({k.lower(): v for k, v in want.items()})
        if any(g(d, k) != v for k, v in exp.items()):
            continue
        out.append(dict(fid=ref, name=name, row=row, d=d, base=base))
        if len(out) >= n:
            break
    if len(out) < n:
        inc(r, "need %d unique non-essential untracked loaded market adult(s), found %d" % (n, len(out)))
        return []
    return out


def wait_ess(r, fid, level, timeout):
    """Poll EssProbeX until IEB_Ess >= level (2 = confirmed). Returns the last dict (or None)."""
    end, d = time.time() + timeout, None
    while time.time() < end:
        d = ex(r, fid)
        if d and g(d, "ieb_ess") >= level:
            return d
        time.sleep(2)
    return d


