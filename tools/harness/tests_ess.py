def _table(rows):
    """rows: list of (base, any, mode). JsonUtil schema (LoadWindows): int rows; formList w_quest, w_base; intList w_any,
    w_mode, w_lo, w_hi, all N long."""
    return {"int": {"rows": len(rows)},
            "formList": {"w_quest": [SYNTH_Q] * len(rows), "w_base": [BASE_FORM(b) for b, _, _ in rows]},
            "intList": {"w_any": [a for _, a, _ in rows], "w_mode": [m for _, _, m in rows],
                        "w_lo": [SYNTH_LO] * len(rows), "w_hi": [-1] * len(rows)}}


def table_json(name):
    """The content of a generated table (None for rows0 / none: not generated here)."""
    bases = [b for _, b in POOL]
    if name == "synth0":
        return _table([(b, 0, 0) for b in bases])
    if name == "synth1":
        return _table([(b, 0, 1) for b in bases])
    if name == "synth1any":
        return _table([(bases[0], 1, 1)])
    if name == "bad_lists":
        t = _table([(bases[0], 0, 0), (bases[1], 0, 0)])
        t["intList"]["w_hi"] = [-1]                                 # one entry short: IntListCount != rows -> bad=lists
        return t
    return None


def make_tables(log=print):
    """Write the generated table files (not rows0). Idempotent; private_out is outside C:\\Nolvus."""
    os.makedirs(PRIV, exist_ok=True)
    for name in ("synth0", "synth1", "synth1any", "bad_lists"):
        data = json.dumps(table_json(name), indent=1).encode("utf-8") + b"\n"
        p = TABLE_SRC[name]
        if not os.path.exists(p) or open(p, "rb").read() != data:
            with open(p, "wb") as f:
                f.write(data)
        log("TABLE %s: %s (%d bytes)" % (name, os.path.basename(p), len(data)))


def current_table():
    """Which table the game would read, from the installed file's content: none / bad / bad_lists / rows0 / synth0 /
    synth1 / synth1any / other."""
    if not os.path.exists(TABLE_DST):
        return "none"
    try:
        j = json.load(open(TABLE_DST, encoding="utf-8"))
        rows = j["int"]["rows"]
        fl, il = j.get("formList", {}), j.get("intList", {})
        lens = [len(fl.get(k, [])) for k in ("w_quest", "w_base")] + [len(il.get(k, [])) for k in ("w_any", "w_mode", "w_lo", "w_hi")]
    except (ValueError, KeyError, OSError):
        return "bad"
    if any(n != rows for n in lens):
        return "bad_lists"
    if rows == 0:
        return "rows0"
    modes, anys = set(il["w_mode"]), set(il["w_any"])
    if modes == {0} and anys == {0}:
        return "synth0"
    if modes == {1} and anys == {0}:
        return "synth1"
    if modes == {1} and anys == {1}:
        return "synth1any"
    return "other"


def install_table(name, log=print):
    """Install table `name` (none / rows0 / synth0 / synth1 / synth1any / bad_lists) as the live ess_windows.json. Only with
    the game, MO2 and the loader closed. Backs up whatever was there (once per call). True when read back byte for byte."""
    if game.procs():
        log("TABLE install refused: %s still running" % sorted(game.procs()))
        return False
    if name != "none":
        if name in ("synth0", "synth1", "synth1any", "bad_lists"):
            make_tables(lambda m: None)
        src = TABLE_SRC.get(name)
        if not src or not os.path.exists(src):
            log("TABLE install refused: no source file for %s (%s)" % (name, src))
            return False
    if os.path.exists(TABLE_DST):
        os.makedirs(BACKUP_DIR, exist_ok=True)
        shutil.copy2(TABLE_DST, BACKUP_DIR + "ess_windows_%s.json" % time.strftime("%Y%m%d-%H%M%S"))
    if name == "none":
        if os.path.exists(TABLE_DST):
            os.remove(TABLE_DST)
        ok = not os.path.exists(TABLE_DST)
    else:
        data = open(TABLE_SRC[name], "rb").read()
        with open(TABLE_DST, "wb") as f:
            f.write(data)
        ok = open(TABLE_DST, "rb").read() == data
    log("TABLE install %s: %s (live table reads as %s)" % (name, "verified" if ok else "WRITE FAILED", current_table()))
    return ok and current_table() == name


def require_table(r, want):
    """Self-check: the installed table is the group's. INCONCLUSIVE (False) otherwise: run through `tests_ess.py run`."""
    cur = current_table()
    if cur != want:
        inc(r, "installed ess_windows.json reads as '%s', this test needs '%s' (run block E through tests_ess.py run)" % (cur, want))
        return False
    return True


