def e_nff(r):
    """T-EMPTY, unique non-essential NPC (not in nwsFF_EssFac): NFF recruit -> within 2 sweeps ESS_APPLY route=nff base_was=0,
    then ESS_CONFIRM by=2; base essential; in nwsFF_EssFac with rank 1 if protected before else 0; IEB_Ess=2 IEB_EssBy=2
    IEB_EssKeep=1 IEB_EssAuth=0. INFERRED: the NFF MCM toggle state is the nwsFF_EssFac membership (ExScript :461-485), so
    the screenshot is replaced by the faction read."""
    if not require_table(r, "rows0"):
        return
    pool = pick_npcs(r)
    if not pool:
        return
    n = pool[0]
    prot0 = g(n["d"], "baseprot")
    s = snap(r, [n["fid"]])
    checkpoint(r)
    t = tail("papyrus")
    try:
        r.ctl("NFFRecruit", [s32(n["fid"])])
        ap = t.wait(r"(?i)\[IEB\] ESS_APPLY actor=%s route=nff base_was=0" % re.escape(n["name"]), APPLY_S)
        r.check(bool(ap), "ESS_APPLY route=nff base_was=0 within %d s" % APPLY_S)
        cf = t.wait(r"(?i)\[IEB\] ESS_CONFIRM actor=%s by=2" % re.escape(n["name"]), CONFIRM_S)
        r.check(bool(cf), "ESS_CONFIRM by=2 within %d s" % CONFIRM_S)
        d = ex(r, n["fid"])
        if d:
            r.check(g(d, "baseess") == 1, "base essential")
            r.check(g(d, "fac") == 1 and g(d, "rank") == (1 if prot0 else 0),
                    "in nwsFF_EssFac with rank %d (protected before: %d); NFF toggle reads ON" % (g(d, "rank"), prot0))
            r.check((g(d, "ieb_ess"), g(d, "ieb_essby"), g(d, "ieb_esskeep"), g(d, "ieb_essauth")) == (2, 2, 1, 0),
                    "IEB_Ess/By/Keep/Auth = 2/2/1/0 (%s/%s/%s/%s)" % (d.get("ieb_ess"), d.get("ieb_essby"), d.get("ieb_esskeep"), d.get("ieb_essauth")))
        finish(r, s, [n["fid"]], [n["fid"]], t.read())
    finally:
        common_cleanup(r, n, nff=True)


