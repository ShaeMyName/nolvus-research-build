def _tbl(r, table, bad):
    if not require_table(r, table):
        return
    pool = pick_npcs(r)
    if not pool:
        return
    n = pool[0]
    base0 = g(n["d"], "baseess")
    checkpoint(r)
    t = tail("papyrus")                       # one WARN per LOAD: this test makes its own load
    if not game.load(r, "T0", settle_probe(r)):
        return inc(r, "reload of T0 failed")
    ie_test_settings(r)
    con(r, "%08X.moveto player" % n["fid"])
    time.sleep(3)
    try:
        m = t.wait(r"(?i)\[IEB\] WARN ESS_TABLE bad=%s" % bad, 90)
        r.check(bool(m), "WARN ESS_TABLE bad=%s logged after the load" % bad)
        r.ctl("NFFRecruit", [s32(n["fid"])])
        sweeps(3)
        txt = t.read()
        r.check(len(re.findall(r"(?i)\[IEB\] WARN ESS_TABLE", txt)) == 1, "exactly one WARN ESS_TABLE for this load (%d)"
                % len(re.findall(r"(?i)\[IEB\] WARN ESS_TABLE", txt)))
        r.check(not has_line(txt, r"ESS_APPLY"), "no ESS_APPLY while the table is bad")
        r.check(not has_line(txt, r"ESS_TABLE rows="), "no 'ESS_TABLE rows=' (valid-table) line")
        d1 = ex(r, n["fid"])
        if d1:
            r.check(g(d1, "baseess") == base0 and g(d1, "ieb_ess") == -1, "base flag unchanged (%s -> %s), no IEB_Ess key" % (base0, d1.get("baseess")))
        unexpected(r, txt, allow=(r"ESS_TABLE bad=%s" % bad,))
    finally:
        nff_dismiss(r, n["fid"])


