def ex(r, fid):
    """EssProbeX as a dict of lower-case keys (ints as strings; -1 = key absent). None if the line never came."""
    m = ctl_line(r, "EssProbeX", [s32(fid)], r"(?i)\[IEB-TEST\] ESSX (%s) ([^\r\n]*)" % fid_any_rx(fid), 15)
    if not m:
        return None
    d = {k.lower(): v for k, v in KV.findall(m.group(2))}
    r.log("  ess %s: baseEss=%s prot=%s fac=%s/%s ess=%s by=%s keep=%s auth=%s opt=%s susp=%s sawrote=%s fail=%s roster=%s slot=%s"
          % (hx(fid), d.get("baseess"), d.get("baseprot"), d.get("fac"), d.get("rank"), d.get("ieb_ess"), d.get("ieb_essby"),
             d.get("ieb_esskeep"), d.get("ieb_essauth"), d.get("ieb_essoptout"), d.get("ieb_esssusp"), d.get("ieb_esssawrote"),
             d.get("ieb_essfail"), d.get("saroster"), d.get("slot")))
    return d


def g(d, k, dflt=-9):
    try:
        return int(d.get(k.lower(), dflt))
    except (TypeError, ValueError):
        return dflt


def ess_ids(r):
    """EssList: dict(n, fail, req, ids = set of normalised FormIDs) or None."""
    t = tail("papyrus")
    r.ctl("EssList")
    m = t.wait(r"(?i)\[IEB-TEST\] ESSLIST n=(\d+) fail=(\d+) req=(\d+) ids=([^\r\n]*)", 15)
    if not m:
        return None
    return dict(n=int(m.group(1)), fail=int(m.group(2)), req=int(m.group(3)),
                ids={fid_norm(x) for x in re.findall(r"0x[0-9A-Fa-f]+", m.group(4))})


def rank_of(r, fid):
    d = rank(r, fid)
    return iv(d, "r") if d else None


def n_lines(text, tag, name, extra=""):
    return len(re.findall(r"(?i)\[IEB\] %s actor=%s\b%s" % (tag, re.escape(name), extra), text))


def has_line(text, rx):
    return re.search(r"(?i)\[IEB\] " + rx, text) is not None


def unexpected(r, text, allow=()):
    bad = [l for l in re.findall(r"(?i)\[IEB\] (?:ERROR|WARN ESS_)[^\r\n]*", text) if not any(re.search(a, l, re.I) for a in allow)]
    r.check(not bad, "no unexpected [IEB] ERROR / WARN ESS_ line (%d)" % len(bad))


def snap(r, fids):
    return dict(ids=ess_ids(r), rank={f: rank_of(r, f) for f in fids})


def finish(r, s, fids, expect_new, text, allow=()):
    """The assertions every test shares (plan 'Common setup'): list gained exactly the expected actors, RankSync's rank
    unchanged, no unexpected error/WARN lines."""
    now = ess_ids(r)
    if s["ids"] is None or now is None:
        inc(r, "EssList unreadable")
    else:
        new = now["ids"] - s["ids"]["ids"]
        r.check(new == {fid_norm(f) for f in expect_new}, "IEB_EssList gained exactly the expected actors (%d new, %d expected)"
                % (len(new), len(expect_new)))
    for f in fids:
        r1 = rank_of(r, f)
        if s["rank"].get(f) is None or r1 is None:
            inc(r, "rank unreadable for 0x%s" % hx(f))
        else:
            r.check(r1 == s["rank"][f], "RankSync rank unchanged for 0x%s (%s -> %s)" % (hx(f), s["rank"][f], r1))
    unexpected(r, text, allow)


