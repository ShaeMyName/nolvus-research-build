@test("E-REQ", "E", reload=True)
def e_req(r):
    """The recruit-event request path: SA's own 'recruit' signal (SARecruitEvent) for an NPC that is not yet on any route sets
    IEB_EssReq = 3 and queues the actor; the sweep then runs every tick (not the 5-tick slot) so the 3 look-agains finish
    in under ~9 s (a slot-only cadence needs ~15 s), after which IEB_EssReqList is empty and the key is gone. INFERRED:
    IEB_PollSeconds = 1 and ~1-2 s polling resolution."""
    if not require_table(r, "rows0"):
        return
    pool = pick_npcs(r)
    if not pool:
        return
    n = pool[0]
    l0 = ess_ids(r)
    if not l0 or l0["req"] != 0:
        return inc(r, "IEB_EssReqList not empty at start (%s)" % (l0 and l0["req"]))
    checkpoint(r)
    try:
        t0 = time.time()
        r.ctl("SARecruitEvent", [s32(n["fid"])])
        first, done = None, None
        while time.time() - t0 < 25:
            d = ex(r, n["fid"])
            if d and first is None and g(d, "ieb_essreq") >= 1:
                first = time.time() - t0
            if d and g(d, "ieb_essreq") == -1 and first is not None:
                done = time.time() - t0
                break
        r.log("  request path: key first seen at %.1f s, gone at %s s" % (first or -1, "%.1f" % done if done else "never"))
        r.check(first is not None, "IEB_EssReq set by the recruit event")
        r.check(done is not None and done <= 9.0, "the request cleared within ~9 s (%.1f s): sweep ran per tick, not per 5-tick slot" % (done or -1))
        l1 = ess_ids(r)
        r.check(bool(l1) and l1["req"] == 0, "IEB_EssReqList empty afterwards")
        d2 = ex(r, n["fid"])
        if d2:
            r.check(g(d2, "ieb_ess") == -1 and g(d2, "baseess") == 0, "the NPC was not tracked or changed (never on a route)")
    finally:
        common_cleanup(r, n)


